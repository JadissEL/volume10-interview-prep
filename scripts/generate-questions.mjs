/**
 * Génère src/data/questions.ts — 100 questions en français.
 * Exécuter : node scripts/generate-questions.mjs
 */
import { writeFileSync } from 'fs'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'
import { BANK_FR, CATEGORIES_FR, META_FR, VARIANTS_FR } from './bank-fr.mjs'

const __dirname = dirname(fileURLToPath(import.meta.url))

const questions = []
let n = 1
for (const cat of CATEGORIES_FR) {
  const items = BANK_FR[cat.id]
  if (!items || items.length !== cat.count) {
    throw new Error(`Catégorie ${cat.id} : attendu ${cat.count}, reçu ${items?.length ?? 0}`)
  }
  for (const [question, answerBullets] of items) {
    const id = `q${String(n).padStart(3, '0')}`
    const extra = META_FR[id] ?? {}
    const variants = VARIANTS_FR[id] ?? {}
    const intro = question.split('?')[0]
    questions.push({
      id,
      categoryId: cat.id,
      question,
      answerBullets,
      fullScript: `Ouverture : « ${intro} ? » — Voici comment je le cadre pour Volume10.\n\n${answerBullets.map((b, i) => `${i + 1}. ${b}`).join('\n')}\n\nConclusion : Relier à « donner de l'espace aux idées » — écouter, provoquer avec tact, livrer des résultats prêts à l'action avec mesure d'impact.`,
      tags: [cat.label],
      ...extra,
      ...variants,
    })
    n++
  }
}

if (questions.length !== 100) {
  throw new Error(`Attendu 100 questions, obtenu ${questions.length}`)
}

const out = `/* AUTO-GENERATED by scripts/generate-questions.mjs — ne pas modifier à la main sauf intention */
import type { InterviewQuestion } from './types';

export const CATEGORIES = ${JSON.stringify(CATEGORIES_FR, null, 2)} as const;

export const questions: InterviewQuestion[] = ${JSON.stringify(questions, null, 2)};
`

writeFileSync(join(__dirname, '../src/data/questions.ts'), out, 'utf8')
console.log(`Écrit ${questions.length} questions dans src/data/questions.ts`)
